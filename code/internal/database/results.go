package database

import (
	"context"
	"fmt"
	"strings"

	"waste-routing/internal/models"
)

const upsertSourceAssignmentSQL = `
INSERT INTO waste_routing.source_assignments (
    run_id,
    waste_source_id,
    destination_transfer_station_id,
    destination_plant_id,
    waste_amount,
    distance_km
) VALUES ($1, $2, $3, $4, $5, $6)
ON CONFLICT (run_id, waste_source_id) DO UPDATE SET
    destination_transfer_station_id = EXCLUDED.destination_transfer_station_id,
    destination_plant_id = EXCLUDED.destination_plant_id,
    waste_amount = EXCLUDED.waste_amount,
    distance_km = EXCLUDED.distance_km`

const selectSourceAssignmentSQL = `
SELECT
    waste_source_id,
    assignment_type,
    COALESCE(destination_transfer_station_id, destination_plant_id),
    waste_amount,
    distance_km,
    transport_cost
FROM waste_routing.source_assignments`

const upsertTransferFlowSQL = `
INSERT INTO waste_routing.transfer_flows (
    run_id,
    transfer_station_id,
    plant_id,
    waste_amount,
    distance_km
) VALUES ($1, $2, $3, $4, $5)
ON CONFLICT (run_id, transfer_station_id, plant_id) DO UPDATE SET
    waste_amount = EXCLUDED.waste_amount,
    distance_km = EXCLUDED.distance_km`

const selectTransferFlowSQL = `
SELECT
    transfer_station_id,
    plant_id,
    waste_amount,
    distance_km,
    transport_cost
FROM waste_routing.transfer_flows`

// UpsertSourceAssignment inserts or updates one source assignment for a run.
// TransportCost is generated by PostgreSQL and is ignored on input.
func (repository *Repository) UpsertSourceAssignment(
	ctx context.Context,
	runID int64,
	assignment models.SourceAssignment,
) error {
	arguments, err := sourceAssignmentArguments(runID, assignment)
	if err != nil {
		return err
	}
	if _, err := repository.pool.Exec(ctx, upsertSourceAssignmentSQL, arguments...); err != nil {
		return fmt.Errorf("upsert source assignment for run %d and source %q: %w", runID, assignment.SourceID, err)
	}
	return nil
}

// UpsertSourceAssignments writes all assignments atomically in bounded batches.
func (repository *Repository) UpsertSourceAssignments(
	ctx context.Context,
	runID int64,
	assignments []models.SourceAssignment,
) error {
	return repository.executeBatchTransaction(ctx, "upsert source assignments", len(assignments), func(index int) (batchStatement, error) {
		arguments, err := sourceAssignmentArguments(runID, assignments[index])
		if err != nil {
			return batchStatement{}, err
		}
		return batchStatement{query: upsertSourceAssignmentSQL, args: arguments}, nil
	})
}

// GetSourceAssignment returns one source assignment from a calculation run.
func (repository *Repository) GetSourceAssignment(
	ctx context.Context,
	runID int64,
	sourceID string,
) (models.SourceAssignment, error) {
	assignment, err := scanSourceAssignment(repository.pool.QueryRow(
		ctx,
		selectSourceAssignmentSQL+` WHERE run_id = $1 AND waste_source_id = $2`,
		runID,
		sourceID,
	))
	if err != nil {
		return models.SourceAssignment{}, mapRowError(
			fmt.Sprintf("get source assignment for run %d and source %q", runID, sourceID),
			err,
		)
	}
	return assignment, nil
}

// ListSourceAssignments returns all source assignments for one run.
func (repository *Repository) ListSourceAssignments(
	ctx context.Context,
	runID int64,
) ([]models.SourceAssignment, error) {
	rows, err := repository.pool.Query(
		ctx,
		selectSourceAssignmentSQL+` WHERE run_id = $1 ORDER BY waste_source_id`,
		runID,
	)
	if err != nil {
		return nil, fmt.Errorf("list source assignments for run %d: query: %w", runID, err)
	}
	defer rows.Close()

	assignments := make([]models.SourceAssignment, 0)
	for rows.Next() {
		assignment, err := scanSourceAssignment(rows)
		if err != nil {
			return nil, fmt.Errorf("list source assignments for run %d: scan row: %w", runID, err)
		}
		assignments = append(assignments, assignment)
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("list source assignments for run %d: iterate rows: %w", runID, err)
	}
	return assignments, nil
}

