func sourceAssignmentArguments(runID int64, assignment models.SourceAssignment) ([]any, error) {
	if runID <= 0 {
		return nil, fmt.Errorf("%w: run ID must be positive", ErrInvalidAssignment)
	}
	if strings.TrimSpace(assignment.SourceID) == "" || strings.TrimSpace(assignment.DestinationID) == "" {
		return nil, fmt.Errorf("%w: source and destination IDs are required", ErrInvalidAssignment)
	}

	var transferStationID any
	var plantID any
	switch assignment.DestinationType {
	case models.AssignmentToTransferStation:
		transferStationID = assignment.DestinationID
	case models.AssignmentToPlant:
		plantID = assignment.DestinationID
	default:
		return nil, fmt.Errorf(
			"%w: unsupported destination type %q",
			ErrInvalidAssignment,
			assignment.DestinationType,
		)
	}

	return []any{
		runID,
		assignment.SourceID,
		transferStationID,
		plantID,
		assignment.WasteAmount,
		assignment.DistanceKM,
	}, nil
}

func transferFlowArguments(runID int64, flow models.TransferFlow) ([]any, error) {
	if runID <= 0 {
		return nil, fmt.Errorf("transfer flow: run ID must be positive")
	}
	if strings.TrimSpace(flow.TransferStationID) == "" || strings.TrimSpace(flow.PlantID) == "" {
		return nil, fmt.Errorf("transfer flow: station and plant IDs are required")
	}
	return []any{
		runID,
		flow.TransferStationID,
		flow.PlantID,
		flow.WasteAmount,
		flow.DistanceKM,
	}, nil
}

func scanSourceAssignment(scanner rowScanner) (models.SourceAssignment, error) {
	var assignment models.SourceAssignment
	var destinationType string
	if err := scanner.Scan(
		&assignment.SourceID,
		&destinationType,
		&assignment.DestinationID,
		&assignment.WasteAmount,
		&assignment.DistanceKM,
		&assignment.TransportCost,
	); err != nil {
		return models.SourceAssignment{}, err
	}
	assignment.DestinationType = models.AssignmentDestinationType(destinationType)
	return assignment, nil
}

func scanTransferFlow(scanner rowScanner) (models.TransferFlow, error) {
	var flow models.TransferFlow
	if err := scanner.Scan(
		&flow.TransferStationID,
		&flow.PlantID,
		&flow.WasteAmount,
		&flow.DistanceKM,
		&flow.TransportCost,
	); err != nil {
		return models.TransferFlow{}, err
	}
	return flow, nil
}
